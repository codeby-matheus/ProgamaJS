let numero = +prompt(
  "fala um numero de 1 a 12, cada numero representando um mês",
);

switch (numero) {
  case 1:
    alert("é janeiro");
    break;
  case 2:
    alert("é fevereiro");
    break;
  case 3:
    alert("é março");
    break;
  case 4:
    alert("é abril");
    break;
  case 5:
    alert("é maio");
    break;
  case 6:
    alert("é junho");
    break;
  case 7:
    alert("é julho");
    break;
  case 8:
    alert("é agosto");
    break;
  case 9:
    alert("é setembro");
    break;
  case 10:
    alert("é outubro");
    break;
  case 11:
    alert("é novembro");
    break;
  case 12:
    alert("é dezembro");
    break;
  default:
    alert("número inválido! digite apenas números de 1 a 12.");
}
